package org.ternhdl.formal;

import java.util.*;
import org.ternhdl.core.*;
import org.ternhdl.encode.*;

/**
 * Formal miter between two modules with the same encoded ports: shared inputs, legality assumptions on every input
 * digit, equality assertions on the compared ports, and (for sequential designs) equal register state assumed in
 * the first cycle. Port widths come from the design that defines the interface.
 */
public final class Miter {
    private Miter() { }

    /**
     * @param iface design defining inputs/outputs (and dbg ports when allNodes)
     * @param left module name of the first instance, right of the second
     * @param allNodes compare every dbg_ port (both modules must expose all nodes of iface)
     */
    public static String emit(Design iface, Encoding enc, String left, String right, boolean allNodes, boolean hasClk) {
        iface.finish();
        StringBuilder s = new StringBuilder("// Generated by TernHDL Miter\nmodule t_miter (\n");
        List<String> ports = new ArrayList<>();
        if (hasClk) ports.add("input logic clk");
        for (var en : iface.inputs().entrySet()) ports.add("input logic " + range(iface.node(en.getValue()).type()) + en.getKey());
        for (int i = 0; i < ports.size(); i++) s.append("  ").append(ports.get(i)).append(i + 1 < ports.size() ? ",\n" : "\n");
        s.append(");\n");
        List<String[]> cmp = new ArrayList<>();   // {port, width-range}
        for (var en : iface.outputs().entrySet()) cmp.add(new String[]{en.getKey(), range(iface.node(en.getValue()).type())});
        if (allNodes) for (Node nd : iface.nodes()) cmp.add(new String[]{SvEmitter.dbg(nd.id()), range(nd.type())});
        for (String[] c : cmp) {
            s.append("  logic ").append(c[1]).append("t_l_").append(c[0]).append(", t_r_").append(c[0]).append(";\n");
        }
        for (String side : new String[]{"l", "r"}) {
            s.append("  ").append(side.equals("l") ? left : right).append(" u_").append(side).append(" (");
            List<String> conn = new ArrayList<>();
            if (hasClk) conn.add(".clk(clk)");
            for (String in : iface.inputs().keySet()) conn.add("." + in + "(" + in + ")");
            for (String[] c : cmp) conn.add("." + c[0] + "(t_" + side + "_" + c[0] + ")");
            s.append(String.join(", ", conn)).append(");\n");
        }
        String ill = "2'b" + (enc.illegal >> 1 & 1) + (enc.illegal & 1);
        s.append("  always @* begin\n");
        for (var en : iface.inputs().entrySet()) {
            Type t = iface.node(en.getValue()).type();
            if (t.isBit()) continue;
            for (int i = 0; i < t.width(); i++) s.append("    assume (").append(en.getKey()).append("[").append(2 * i + 1).append(":").append(2 * i).append("] != ").append(ill).append(");\n");
        }
        for (String[] c : cmp) s.append("    assert (t_l_").append(c[0]).append(" == t_r_").append(c[0]).append(");\n");
        s.append("  end\n");
        if (hasClk && allNodes) {
            s.append("  logic t_init = 1'b1;\n  always @(posedge clk) t_init <= 1'b0;\n  always @* if (t_init) begin\n");
            for (Node nd : iface.nodes()) if (nd.op() == Op.REG) {
                String p = SvEmitter.dbg(nd.id());
                s.append("    assume (t_l_").append(p).append(" == t_r_").append(p).append(");\n");
                if (!nd.type().isBit()) for (int i = 0; i < nd.type().width(); i++)
                    s.append("    assume (t_l_").append(p).append("[").append(2 * i + 1).append(":").append(2 * i).append("] != ").append(ill).append(");\n");
            }
            s.append("  end\n");
        }
        s.append("endmodule\n");
        return s.toString();
    }

    /**
     * Miter for two different designs with the same port interface (e.g. RTL vs mapped netlist). Both are emitted with
     * every node exposed; pairs {leftRegNode, leftDigit, rightRegNode, rightDigit} start equal and legal; outputs are
     * asserted equal in every cycle.
     */
    public static String emitPaired(Design l, Design r, Encoding enc, String lmod, String rmod, List<int[]> pairs, boolean hasClk) {
        l.finish(); r.finish();
        String ill = "2'b" + (enc.illegal >> 1 & 1) + (enc.illegal & 1);
        StringBuilder s = new StringBuilder("// Generated by TernHDL Miter (paired state)\nmodule t_miter (\n");
        List<String> ports = new ArrayList<>();
        if (hasClk) ports.add("input logic clk");
        for (var en : l.inputs().entrySet()) ports.add("input logic " + range(l.node(en.getValue()).type()) + en.getKey());
        s.append("  ").append(String.join(",\n  ", ports)).append("\n);\n");
        for (String side : new String[]{"l", "r"}) {
            Design dd = side.equals("l") ? l : r;
            List<String> conn = new ArrayList<>();
            if (hasClk) conn.add(".clk(clk)");
            for (String in : dd.inputs().keySet()) conn.add("." + in + "(" + in + ")");
            for (var en : dd.outputs().entrySet()) {
                s.append("  logic ").append(range(dd.node(en.getValue()).type())).append("t_").append(side).append("_").append(en.getKey()).append(";\n");
                conn.add("." + en.getKey() + "(t_" + side + "_" + en.getKey() + ")");
            }
            for (Node nd : dd.nodes()) {
                s.append("  logic ").append(range(nd.type())).append("t_").append(side).append("d").append(nd.id()).append(";\n");
                conn.add("." + SvEmitter.dbg(nd.id()) + "(t_" + side + "d" + nd.id() + ")");
            }
            s.append("  ").append(side.equals("l") ? lmod : rmod).append(" u_").append(side).append(" (").append(String.join(", ", conn)).append(");\n");
        }
        s.append("  always @* begin\n");
        for (var en : l.inputs().entrySet()) {
            Type t = l.node(en.getValue()).type();
            if (!t.isBit()) for (int i = 0; i < t.width(); i++) s.append("    assume (").append(en.getKey()).append("[").append(2 * i + 1).append(":").append(2 * i).append("] != ").append(ill).append(");\n");
        }
        for (String o : l.outputs().keySet()) s.append("    assert (t_l_").append(o).append(" == t_r_").append(o).append(");\n");
        s.append("  end\n");
        if (hasClk && !pairs.isEmpty()) {
            s.append("  logic t_init = 1'b1;\n  always @(posedge clk) t_init <= 1'b0;\n  always @* if (t_init) begin\n");
            for (int[] p : pairs) {
                String a = "t_ld" + p[0] + (l.node(p[0]).type().isBit() ? "" : "[" + (2 * p[1] + 1) + ":" + (2 * p[1]) + "]");
                String b = "t_rd" + p[2] + (r.node(p[2]).type().isBit() ? "" : "[" + (2 * p[3] + 1) + ":" + (2 * p[3]) + "]");
                s.append("    assume (").append(a).append(" == ").append(b).append(");\n");
                if (!l.node(p[0]).type().isBit()) s.append("    assume (").append(a).append(" != ").append(ill).append(");\n");
            }
            s.append("  end\n");
        }
        s.append("endmodule\n");
        return s.toString();
    }

    private static String range(Type t) { return t.isBit() ? "" : "[" + (2 * t.width() - 1) + ":0] "; }
}
