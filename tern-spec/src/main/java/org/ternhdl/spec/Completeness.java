package org.ternhdl.spec;

import java.util.*;
import java.util.function.*;

/**
 * Exhaustive functional-completeness analysis of the ternary cell basis.
 *
 * Value indices: N=0, O=1, P=2 (balanced -1, 0, +1). A function of k arguments is a table of 3^k entries,
 * indexed with the first argument most significant.
 *
 * Two independent methods:
 *  - closure(): brute force. Generate all binary functions of (x, y) reachable from {x, y} (and optionally constants)
 *    by composing gates; the set is complete iff all 3^9 = 19683 binary functions are reached.
 *  - slupecki(): fast criterion. Complete iff all 27 unary functions are generated and some gate is
 *    essentially binary-or-more and takes all three values.
 * The tests check that both agree.
 */
public final class Completeness {
    public record Gate(String name, int arity, int[] table) {
        public int eval(int... a) { int i = 0; for (int x : a) i = i * 3 + x; return table[i]; }
    }

    private static Gate u(String n, IntUnaryOperator f) {
        int[] t = new int[3];
        for (int a = 0; a < 3; a++) t[a] = f.applyAsInt(a - 1) + 1;
        return new Gate(n, 1, t);
    }
    private static Gate b(String n, IntBinaryOperator f) {
        int[] t = new int[9];
        for (int a = 0; a < 3; a++) for (int c = 0; c < 3; c++) t[a * 3 + c] = f.applyAsInt(a - 1, c - 1) + 1;
        return new Gate(n, 2, t);
    }

    public static final Gate STI = u("STI", x -> -x);
    public static final Gate PTI = u("PTI", x -> x == 1 ? -1 : 1);
    public static final Gate NTI = u("NTI", x -> x == -1 ? 1 : -1);
    public static final Gate ICI = u("ICI", x -> x == 1 ? -1 : x + 1);
    public static final Gate DCI = u("DCI", x -> x == -1 ? 1 : x - 1);
    public static final Gate ISZERO = u("IsZero", x -> x == 0 ? 1 : -1);
    public static final Gate MIN = b("MIN", Math::min);
    public static final Gate MAX = b("MAX", Math::max);
    public static final Gate ANY = b("ANY", (a, c) -> Math.max(-1, Math.min(1, a + c)));
    public static final Gate CONS = b("CONS", (a, c) -> a == c ? a : 0);
    public static final Gate SUM = b("SUM", (a, c) -> { int s = a + c; return s > 1 ? s - 3 : s < -1 ? s + 3 : s; });
    /** Webb function on indices: max(x, y) + 1 mod 3. */
    public static final Gate WEBB = new Gate("WEBB", 2, webb());
    private static int[] webb() {
        int[] t = new int[9];
        for (int a = 0; a < 3; a++) for (int c = 0; c < 3; c++) t[a * 3 + c] = (Math.max(a, c) + 1) % 3;
        return t;
    }
    /** 3:1 multiplexer with arguments (select, a, b, c): select N -> a, O -> b, P -> c. */
    public static final Gate MUX = new Gate("MUX3", 4, mux());
    private static int[] mux() {
        int[] t = new int[81];
        for (int s = 0; s < 3; s++) for (int a = 0; a < 3; a++) for (int c = 0; c < 3; c++) for (int d = 0; d < 3; d++)
            t[((s * 3 + a) * 3 + c) * 3 + d] = s == 0 ? a : s == 1 ? c : d;
        return t;
    }

    public static final List<Gate> LIBRARY = List.of(STI, PTI, NTI, ICI, DCI, ISZERO, MIN, MAX, ANY, CONS, SUM, MUX);

    // ---------------------------------------------------------------- unary closure

    private static int code1(int[] f) { return f[0] + 3 * f[1] + 9 * f[2]; }
    private static int[] decode1(int c) { return new int[]{c % 3, (c / 3) % 3, c / 9}; }

    /** The set of unary functions (as codes 0..26) generated by the gates, with identity and optional constants. */
    public static BitSet unaryClosure(Collection<Gate> gates, boolean constants) {
        BitSet seen = new BitSet(27);
        seen.set(code1(new int[]{0, 1, 2}));
        if (constants) for (int v = 0; v < 3; v++) seen.set(code1(new int[]{v, v, v}));
        boolean changed = true;
        while (changed) {
            changed = false;
            int[] cur = seen.stream().toArray();
            for (Gate g : gates) {
                int[] idx = new int[g.arity()];
                int total = (int) Math.pow(cur.length, g.arity());
                for (int n = 0; n < total; n++) {
                    int m = n;
                    for (int k = g.arity() - 1; k >= 0; k--) { idx[k] = cur[m % cur.length]; m /= cur.length; }
                    int[] r = new int[3];
                    for (int x = 0; x < 3; x++) {
                        int[] a = new int[g.arity()];
                        for (int k = 0; k < a.length; k++) a[k] = decode1(idx[k])[x];
                        r[x] = g.eval(a);
                    }
                    int c = code1(r);
                    if (!seen.get(c)) { seen.set(c); changed = true; }
                }
            }
        }
        return seen;
    }

    private static boolean essentiallyMultiAndSurjective(Gate g) {
        if (g.arity() < 2) return false;
        boolean[] range = new boolean[3];
        for (int v : g.table()) range[v] = true;
        if (!(range[0] && range[1] && range[2])) return false;
        int essential = 0;
        int n = g.arity();
        for (int pos = 0; pos < n; pos++) {
            int stride = (int) Math.pow(3, n - 1 - pos);
            boolean depends = false;
            for (int i = 0; i < g.table().length && !depends; i++) {
                int digit = (i / stride) % 3;
                if (digit == 0) for (int d = 1; d < 3; d++) if (g.table()[i] != g.table()[i + d * stride]) depends = true;
            }
            if (depends) essential++;
        }
        return essential >= 2;
    }

    /** Fast completeness criterion (Slupecki). */
    public static boolean slupecki(Collection<Gate> gates, boolean constants) {
        if (unaryClosure(gates, constants).cardinality() != 27) return false;
        for (Gate g : gates) if (essentiallyMultiAndSurjective(g)) return true;
        return false;
    }

    // ---------------------------------------------------------------- brute-force closure over binary functions

    private static final int N2 = 19683;
    private static final byte[][] DIG = new byte[N2][9];
    private static final int[] POW3 = new int[9];
    static {
        POW3[0] = 1; for (int i = 1; i < 9; i++) POW3[i] = POW3[i - 1] * 3;
        for (int c = 0; c < N2; c++) { int m = c; for (int p = 0; p < 9; p++) { DIG[c][p] = (byte) (m % 3); m /= 3; } }
    }

    /** Number of binary functions reachable; arity <= 2 gates only (use slupecki() for arity 3+). */
    public static int closure(Collection<Gate> gates, boolean constants) {
        List<Gate> un = new ArrayList<>(), bin = new ArrayList<>();
        for (Gate g : gates) { if (g.arity() == 1) un.add(g); else if (g.arity() == 2) bin.add(g); else throw new IllegalArgumentException("arity " + g.arity()); }
        boolean[] seen = new boolean[N2];
        int[] list = new int[N2];
        int[] n = {0};
        Consumer<Integer> add = c -> { if (!seen[c]) { seen[c] = true; list[n[0]++] = c; } };
        int x = 0, y = 0;
        for (int a = 0; a < 3; a++) for (int c = 0; c < 3; c++) { x += a * POW3[a * 3 + c]; y += c * POW3[a * 3 + c]; }
        add.accept(x); add.accept(y);
        if (constants) for (int v = 0; v < 3; v++) { int k = 0; for (int p = 0; p < 9; p++) k += v * POW3[p]; add.accept(k); }
        for (int head = 0; head < n[0]; head++) {
            int s = list[head];
            for (Gate g : un) { int r = 0; for (int p = 0; p < 9; p++) r += g.table()[DIG[s][p]] * POW3[p]; add.accept(r); }
            for (Gate g : bin) {
                int[] t = g.table();
                for (int i = 0; i <= head; i++) {
                    int o = list[i];
                    int r1 = 0, r2 = 0;
                    for (int p = 0; p < 9; p++) { r1 += t[DIG[s][p] * 3 + DIG[o][p]] * POW3[p]; r2 += t[DIG[o][p] * 3 + DIG[s][p]] * POW3[p]; }
                    add.accept(r1); add.accept(r2);
                }
            }
            // earlier items were combined with s when s was a "new" item only for i<=head; combine later items on their turn
        }
        return n[0];
    }

    // ---------------------------------------------------------------- report

    static List<Gate> pick(Gate... g) { return List.of(g); }

    public static void main(String[] args) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Completeness report (generated by tern-spec Completeness)\n\n");
        sb.append("Values N=0, O=1, P=2. 'closure' = number of the 19683 binary functions reachable by brute force; ");
        sb.append("'Slupecki' = fast criterion; 'const' = tie cells N/O/P available.\n\n");
        sb.append("| Basis | const | closure | complete (brute) | Slupecki |\n|---|---|---|---|---|\n");
        Map<String, List<Gate>> named = new LinkedHashMap<>();
        named.put("{WEBB}", pick(WEBB));
        named.put("{MIN, MAX, STI}  (Kleene)", pick(MIN, MAX, STI));
        named.put("{MIN, MAX, ICI}", pick(MIN, MAX, ICI));
        named.put("{MIN, MAX, STI, PTI, NTI}", pick(MIN, MAX, STI, PTI, NTI));
        named.put("{ANY, CONS, STI}", pick(ANY, CONS, STI));
        named.put("{ANY, SUM, STI}", pick(ANY, SUM, STI));
        named.put("{SUM, MIN, MAX, STI}", pick(SUM, MIN, MAX, STI));
        named.put("{STI, PTI, NTI, ICI, DCI, IsZero, MIN, MAX, ANY, CONS, SUM}", pick(STI, PTI, NTI, ICI, DCI, ISZERO, MIN, MAX, ANY, CONS, SUM));
        for (var e : named.entrySet()) for (boolean k : new boolean[]{false, true}) {
            int c = closure(e.getValue(), k);
            sb.append("| ").append(e.getKey()).append(" | ").append(k).append(" | ").append(c).append(" | ")
              .append(c == N2).append(" | ").append(slupecki(e.getValue(), k)).append(" |\n");
        }
        // single-gate completeness, minimal complete subsets of the library
        for (boolean k : new boolean[]{false, true}) {
            sb.append("\n## Library subsets, const=").append(k).append("\n\n");
            List<Gate> lib = LIBRARY;
            int n = lib.size();
            List<Integer> complete = new ArrayList<>();
            for (int m = 1; m < (1 << n); m++) {
                List<Gate> s = new ArrayList<>();
                for (int i = 0; i < n; i++) if ((m >> i & 1) != 0) s.add(lib.get(i));
                if (slupecki(s, k)) complete.add(m);
            }
            sb.append("Complete subsets: ").append(complete.size()).append(" of ").append((1 << n) - 1).append(".\n\n");
            sb.append("Minimal complete subsets:\n\n");
            for (int m : complete) {
                boolean minimal = true;
                for (int o : complete) if (o != m && (o & m) == o) { minimal = false; break; }
                if (!minimal) continue;
                StringJoiner j = new StringJoiner(", ", "- {", "}");
                for (int i = 0; i < n; i++) if ((m >> i & 1) != 0) j.add(lib.get(i).name());
                sb.append(j).append("\n");
            }
        }
        System.out.print(sb);
    }
}
